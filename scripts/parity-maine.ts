import { tabulateIrv } from '../src/irv.js';
import { MAINE_2018_CD2 as E } from '../src/elections/maine-2018-cd2.js';
const r = tabulateIrv(E.load(), E.candidates, E.rules);
for (const rd of r.rounds) console.log(JSON.stringify(rd));
const fin = r.rounds.at(-1)!.tallies;
const gap = Object.fromEntries(Object.entries(E.certified.final).map(([k, v]) => [k, (fin[k] ?? 0) - v]));
const r1gap = Object.fromEntries(Object.entries(E.certified.round1).map(([k, v]) => [k, r.rounds[0].tallies[k] - v]));
console.log('ballots', r.totalBallots, 'rounds', r.rounds.length, 'winner', r.winner);
console.log('round1 gap', r1gap, 'final gap', gap);
const ok = Object.values(gap).every(v => v === 0) && Object.values(r1gap).every(v => v === 0) && r.rounds.length === E.certified.rounds && r.totalBallots === E.certified.totalBallots;
console.log(ok ? 'PARITY: EXACT' : 'PARITY: MISMATCH'); process.exit(ok ? 0 : 1);
